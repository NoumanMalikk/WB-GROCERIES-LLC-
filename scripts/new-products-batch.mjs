async function fetchJson(url) {
  const res = await fetch(url, {
    headers: { "User-Agent": "WB-Groceries-Storefront/1.0 (catalogue expansion)" },
  });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
}

function pickImage(product) {
  const candidates = [
    product.image_front_url,
    product.image_url,
    product.image_front_small_url,
    product.image_small_url,
    ...(product.selected_images?.front?.display ? Object.values(product.selected_images.front.display) : []),
  ].filter(Boolean);
  return candidates[0] || null;
}

async function resolveImage(item) {
  for (const code of item.codes) {
    try {
      const data = await fetchJson(`https://world.openfoodfacts.org/api/v2/product/${code}.json`);
      if (data.status === 1 && data.product) {
        const url = pickImage(data.product);
        if (url) return { url, code, source: "barcode" };
      }
    } catch {
      /* next */
    }
  }
  const searchUrl =
    "https://world.openfoodfacts.org/cgi/search.pl?" +
    new URLSearchParams({
      search_terms: item.query,
      search_simple: "1",
      action: "process",
      json: "1",
      page_size: "10",
    });
  const data = await fetchJson(searchUrl);
  for (const product of data.products || []) {
    const url = pickImage(product);
    if (url) return { url, code: product.code, source: "search" };
  }
  return null;
}

async function download(url, dest) {
  const res = await fetch(url, {
    headers: { "User-Agent": "WB-Groceries-Storefront/1.0 (catalogue expansion)" },
  });
  if (!res.ok) throw new Error(`download ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(dest, buf);
  return buf.length;
}

