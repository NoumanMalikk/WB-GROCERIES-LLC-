async function main() {
  const report = [];
  for (const item of batch) {
    const dir = path.join(ROOT, "public/products", item.slug);
    fs.mkdirSync(dir, { recursive: true });
    const existingWebp = path.join(dir, "main.webp");
    const existingPng = path.join(dir, "main.png");
    if (fs.existsSync(existingWebp) || fs.existsSync(existingPng)) {
      console.log(`${item.slug} ... SKIP (exists)`);
      report.push({ slug: item.slug, status: "exists" });
      continue;
    }
    process.stdout.write(`${item.slug} ... `);
    try {
      const found = await resolveImage(item);
      if (!found) {
        console.log("NOT FOUND");
        report.push({ slug: item.slug, status: "missing" });
        continue;
      }
      const ext = found.url.includes(".png") ? "png" : found.url.includes(".webp") ? "webp" : "jpg";
      const mainPath = path.join(dir, `main.${ext}`);
      const anglePath = path.join(dir, `angle.${ext}`);
      const size = await download(found.url, mainPath);
      fs.copyFileSync(mainPath, anglePath);
      console.log(`OK (${found.source} ${found.code}) ${size}b`);
      report.push({ slug: item.slug, status: "ok", code: found.code, url: found.url, ext });
      await new Promise((r) => setTimeout(r, 400));
    } catch (err) {
      console.log(`FAIL ${err.message}`);
      report.push({ slug: item.slug, status: "fail", error: String(err.message) });
    }
  }

  const products = batch.map((item, index) => toProductRecord(item, index));
  if (writeJson) {
    fs.writeFileSync(path.join(ROOT, "scripts/new-products.json"), JSON.stringify(products, null, 2));
    console.log(`Wrote scripts/new-products.json (${products.length} products)`);
  }
  fs.writeFileSync(path.join(ROOT, "scripts/new-products-download-report.json"), JSON.stringify(report, null, 2));
  const ok = report.filter((r) => r.status === "ok" || r.status === "exists").length;
  console.log(`\nImages ready: ${ok}/${batch.length}`);
}

main();
